#!/usr/bin/env bash
# Regenerate or verify Python SDK Pydantic models from packages/api-spec/openapi.json.
# Intended to run with cwd = packages/sdk/python (Compose working_dir or local).
set -euo pipefail

PKG_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SPEC="${PKG_ROOT}/../../api-spec/openapi.json"
GENERATED="${PKG_ROOT}/python/openapp_sdk/models/_generated.py"

usage() {
  echo "usage: $0 gen | check" >&2
  exit 2
}

run_codegen_to_tmp() {
  local tmp="$1"
  uv run python -m datamodel_code_generator \
    --input "${SPEC}" \
    --input-file-type openapi \
    --output "${tmp}" \
    --output-model-type pydantic_v2.BaseModel \
    --target-python-version 3.10 \
    --use-standard-collections \
    --use-union-operator \
    --use-annotated \
    --disable-timestamp \
    --collapse-root-models \
    --field-constraints \
    --enum-field-as-literal one \
    --use-schema-description \
    --formatters ruff-format ruff-check
}

cmd_gen() {
  local tmp
  tmp="$(mktemp)"
  run_codegen_to_tmp "${tmp}"
  {
    printf '# @generated by `just sdk::python::openapi-gen` — DO NOT EDIT.\n'
    printf '# Source: packages/api-spec/openapi.json\n\n'
    tail -n +2 "${tmp}"
  } > "${GENERATED}"
  rm -f "${tmp}"
}

cmd_check() {
  local tmp expected
  tmp="$(mktemp)"
  expected="$(mktemp)"
  run_codegen_to_tmp "${tmp}"
  {
    printf '# @generated by `just sdk::python::openapi-gen` — DO NOT EDIT.\n'
    printf '# Source: packages/api-spec/openapi.json\n\n'
    tail -n +2 "${tmp}"
  } > "${expected}"
  if ! diff -u "${GENERATED}" "${expected}" >/dev/null; then
    rm -f "${tmp}" "${expected}"
    echo "openapp_sdk/models/_generated.py is stale vs packages/api-spec/openapi.json." >&2
    echo "Run: just sdk python openapi-gen   (from repo root)" >&2
    exit 1
  fi
  rm -f "${tmp}" "${expected}"
  echo "openapp_sdk/models/_generated.py is up to date."
}

case "${1:-}" in
  gen) cmd_gen ;;
  check) cmd_check ;;
  *) usage ;;
esac
